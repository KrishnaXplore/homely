const LanguageContext = createContext();

// Language names for display
const languageNames = {
    en: 'English',
    hi: 'हिंदी',
    kn: 'ಕನ್ನಡ',
};

// Language codes to full names (for AI)
const languageFullNames = {
    en: 'English',
    hi: 'Hindi',
    kn: 'Kannada',
};

/**
 * LanguageProvider - Provides language context to the app
 */
export const LanguageProvider = ({ children }) => {
    // Get initial language from localStorage or default to 'en'
    const [language, setLanguage] = useState(() => {
        const savedLanguage = localStorage.getItem('homely-language');
        return savedLanguage && translations[savedLanguage] ? savedLanguage : 'en';
    });

    // Save language to localStorage when it changes
    useEffect(() => {
        localStorage.setItem('homely-language', language);
        // Update document lang attribute
        document.documentElement.lang = language;
    }, [language]);

    /**
     * Get translation by key path (e.g., 'nav.home')
     * Supports interpolation with params object (e.g., t('welcome', { name: 'John' }))
     */
    const t = useCallback((keyPath, paramsOrFallback = '', fallback = '') => {
        // Determine if second argument is params object or fallback string
        const params = typeof paramsOrFallback === 'object' ? paramsOrFallback : null;
        const fallbackStr = typeof paramsOrFallback === 'string' ? paramsOrFallback : fallback;
        
        const keys = keyPath.split('.');
        let value = translations[language];
        
        for (const key of keys) {
            if (value && typeof value === 'object' && key in value) {
                value = value[key];
            } else {
                // Try fallback to English
                let fallbackValue = translations.en;
                for (const k of keys) {
                    if (fallbackValue && typeof fallbackValue === 'object' && k in fallbackValue) {
                        fallbackValue = fallbackValue[k];
                    } else {
                        return fallbackStr || keyPath;
                    }
                }
                value = fallbackValue;
                break;
            }
        }
        
        let result = value || fallbackStr || keyPath;
        
        // Handle interpolation: replace {key} with params[key]
        if (params && typeof result === 'string') {
            Object.keys(params).forEach(key => {
                result = result.replace(new RegExp(`\\{${key}\\}`, 'g'), params[key]);
            });
        }
        
        return result;
    }, [language]);

    /**
     * Change language
     */
    const changeLanguage = useCallback((newLang) => {
        if (translations[newLang]) {
            setLanguage(newLang);
        }
    }, []);

    /**
     * Get current language code
     */
    const getCurrentLanguage = useCallback(() => language, [language]);

    /**
     * Get language name for display
     */
    const getLanguageName = useCallback((code = language) => {
        return languageNames[code] || code;
    }, [language]);

    /**
     * Get full language name (for AI)
     */
    const getLanguageFullName = useCallback((code = language) => {
        return languageFullNames[code] || 'English';
    }, [language]);

    /**
     * Get all available languages
     */
    const getAvailableLanguages = useCallback(() => {
        return Object.keys(translations).map(code => ({
            code,
            name: languageNames[code],
            fullName: languageFullNames[code],
        }));
    }, []);

    const value = {
        language,
        t,
        changeLanguage,
        getCurrentLanguage,
        getLanguageName,
        getLanguageFullName,
        getAvailableLanguages,
        translations,
    };

    return (
        <LanguageContext.Provider value={value}>
            {children}
        </LanguageContext.Provider>
    );
};

/**
 * useLanguage - Custom hook to use language context
 */
export const useLanguage = () => {
    const context = useContext(LanguageContext);
    if (!context) {
        throw new Error('useLanguage must be used within a LanguageProvider');
    }
    return context;
};

export default LanguageContext;
